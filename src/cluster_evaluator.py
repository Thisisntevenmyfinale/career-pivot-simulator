"""
LLM Cluster Evaluator
=====================
Addresses the #1 mistake in applied AI: shipping zero-shot outputs without
evaluating whether the model actually did what you needed.

Pattern used here: Generate → Evaluate → Refine (self-improvement loop)

  Round 1: GPT-4o-mini names each cluster from top skills + occupation samples
  Round 2: A SECOND call judges the name (1-10 score, specific critique)
  Round 3: If score < 8, a THIRD call refines using the critique
  Result:  Every cluster name has been evaluated and improved if needed

Why this matters for career pivots:
  Without this, clusters are "Cluster 0" or keyword-soup like
  "sql, python, statistics" — meaningless to a career changer.
  With this, they become "Engineering & Technical Systems" with a tagline
  and a pivot-reachability score: "Reachable from Product roles in ~6 months".

Outputs per cluster:
  name                 — human-readable cluster identity
  tagline              — one-liner describing the career archetype
  pivot_reachability   — 1 (isolated) to 5 (hub) — how pivot-friendly is this cluster
  example_pivot_from   — "If you're coming from X, this cluster is attractive because..."
  eval_score           — the evaluator's quality score (1-10)
  refined              — True if name was improved in round 3
  reasoning            — evaluator's critique (visible in debug panel)
"""

from __future__ import annotations

import json
from typing import Any, Dict, List, Optional


# ─────────────────────────────────────────────────────────────────────────────
# Prompts
# ─────────────────────────────────────────────────────────────────────────────

_NAMING_SYSTEM = """You are an expert labor economist and career counselor.
You are given a cluster of occupations from an O*NET skill-importance matrix.
Your job: give this cluster of occupations a meaningful, memorable name that
career changers would immediately understand.

Output JSON only. No prose. Schema:
{
  "name": "2-4 word cluster identity (e.g. 'Data & Decision Science')",
  "tagline": "One sentence: what these jobs have in common for a career changer",
  "pivot_reachability": <integer 1-5 where 1=very hard to enter, 5=entry-friendly hub>,
  "example_pivot_from": "If you're coming from [role], this cluster is attractive because..."
}"""

_NAMING_USER = """Cluster occupations (sample): {occupations}
Top skills by importance in this cluster: {skills}
Number of occupations in cluster: {n_occupations}"""


_EVAL_SYSTEM = """You are a critical AI output evaluator.
You are given a cluster name and description generated by another model.
Evaluate its quality for a career-change product.

Criteria:
  - Clarity: would a career changer immediately understand this cluster?
  - Accuracy: does the name reflect the actual skills and occupations?
  - Usefulness: does the tagline help someone decide if they want to pivot here?
  - Reachability: is the pivot_reachability score credible?

Output JSON only. Schema:
{
  "score": <integer 1-10>,
  "critique": "One specific sentence on what's wrong or weak (or 'None' if excellent)",
  "improvement": "Specific suggestion to improve the name/tagline (or 'None' if excellent)"
}"""

_EVAL_USER = """Cluster name: "{name}"
Tagline: "{tagline}"
Pivot reachability: {pivot_reachability}/5
Sample occupations: {occupations}
Top skills: {skills}"""


_REFINE_SYSTEM = """You are an expert labor economist and career counselor.
You previously named a cluster of occupations. A quality evaluator found issues.
Improve your naming using the specific critique provided.

Output JSON only. Same schema as before:
{
  "name": "2-4 word cluster identity",
  "tagline": "One sentence: what these jobs have in common for a career changer",
  "pivot_reachability": <integer 1-5>,
  "example_pivot_from": "If you're coming from [role], this cluster is attractive because..."
}"""

_REFINE_USER = """Original name: "{name}"
Original tagline: "{tagline}"
Evaluator critique: "{critique}"
Evaluator improvement suggestion: "{improvement}"
Cluster occupations (sample): {occupations}
Top skills: {skills}"""


# ─────────────────────────────────────────────────────────────────────────────
# Core evaluation loop
# ─────────────────────────────────────────────────────────────────────────────

def _call_json(client: Any, system: str, user: str, temperature: float = 0.3) -> Optional[Dict]:
    """Single GPT call, returns parsed JSON or None on failure."""
    try:
        resp = client.chat.completions.create(
            model="gpt-4o-mini",
            temperature=temperature,
            messages=[
                {"role": "system", "content": system},
                {"role": "user",   "content": user},
            ],
            response_format={"type": "json_object"},
        )
        return json.loads(resp.choices[0].message.content)
    except Exception:
        return None


def evaluate_cluster(
    client: Any,
    *,
    cluster_id: str,
    top_skills: List[str],
    sample_occupations: List[str],
    n_occupations: int,
    min_eval_score: int = 8,
) -> Dict[str, Any]:
    """
    Run the Generate → Evaluate → Refine loop for one cluster.

    Returns a dict with: name, tagline, pivot_reachability, example_pivot_from,
                         eval_score, refined, reasoning, cluster_id
    """
    occs_str  = ", ".join(sample_occupations[:12])
    skills_str = ", ".join(top_skills[:8])

    # ── Round 1: Generate ────────────────────────────────────────────────────
    naming = _call_json(
        client,
        _NAMING_SYSTEM,
        _NAMING_USER.format(
            occupations=occs_str,
            skills=skills_str,
            n_occupations=n_occupations,
        ),
    )
    if not naming:
        return _fallback_cluster(cluster_id, top_skills)

    name     = naming.get("name", f"Cluster {cluster_id}")
    tagline  = naming.get("tagline", "")
    reach    = int(naming.get("pivot_reachability", 3))
    ex_pivot = naming.get("example_pivot_from", "")

    # ── Round 2: Evaluate ────────────────────────────────────────────────────
    evaluation = _call_json(
        client,
        _EVAL_SYSTEM,
        _EVAL_USER.format(
            name=name,
            tagline=tagline,
            pivot_reachability=reach,
            occupations=occs_str,
            skills=skills_str,
        ),
    )

    eval_score = 10
    critique   = "None"
    improvement = "None"
    if evaluation:
        eval_score  = int(evaluation.get("score", 10))
        critique    = evaluation.get("critique", "None")
        improvement = evaluation.get("improvement", "None")

    refined = False

    # ── Round 3: Refine if score below threshold ──────────────────────────────
    if eval_score < min_eval_score and critique != "None" and improvement != "None":
        refined_result = _call_json(
            client,
            _REFINE_SYSTEM,
            _REFINE_USER.format(
                name=name,
                tagline=tagline,
                critique=critique,
                improvement=improvement,
                occupations=occs_str,
                skills=skills_str,
            ),
        )
        if refined_result:
            name     = refined_result.get("name", name)
            tagline  = refined_result.get("tagline", tagline)
            reach    = int(refined_result.get("pivot_reachability", reach))
            ex_pivot = refined_result.get("example_pivot_from", ex_pivot)
            refined  = True

    return {
        "cluster_id":         cluster_id,
        "name":               name,
        "tagline":            tagline,
        "pivot_reachability": reach,
        "example_pivot_from": ex_pivot,
        "eval_score":         eval_score,
        "refined":            refined,
        "reasoning":          critique,
        "top_skills":         top_skills,
    }


def evaluate_all_clusters(
    oai_key: str,
    cluster_themes: Dict[str, Any],
    clusters: Dict[str, int],
    *,
    min_eval_score: int = 8,
) -> Dict[str, Dict[str, Any]]:
    """
    Run the full evaluation loop for all clusters.

    Args:
        oai_key:        OpenAI API key
        cluster_themes: {cluster_id: {"top_skills": [...], ...}}
        clusters:       {occupation_name: cluster_id}
        min_eval_score: threshold below which refinement is triggered

    Returns:
        {cluster_id_str: evaluated_cluster_dict}
    """
    try:
        from openai import OpenAI
        client = OpenAI(api_key=oai_key)
    except Exception:
        return _all_fallbacks(cluster_themes)

    # Build occupation lookup per cluster
    from collections import defaultdict
    by_cluster: Dict[int, List[str]] = defaultdict(list)
    for occ, cid in clusters.items():
        by_cluster[int(cid)].append(str(occ))

    results: Dict[str, Dict[str, Any]] = {}
    for cid_str, theme in cluster_themes.items():
        cid_int = int(cid_str)
        sample_occs = by_cluster.get(cid_int, [])[:12]
        top_skills  = theme.get("top_skills", [])
        n_occ       = len(by_cluster.get(cid_int, []))

        result = evaluate_cluster(
            client,
            cluster_id=cid_str,
            top_skills=top_skills,
            sample_occupations=sample_occs,
            n_occupations=n_occ,
            min_eval_score=min_eval_score,
        )
        results[cid_str] = result

    return results


