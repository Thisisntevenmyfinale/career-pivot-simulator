def _fallback_cluster(cluster_id: str, top_skills: List[str]) -> Dict[str, Any]:
    fb = _FALLBACK_NAMES.get(str(cluster_id), {})
    return {
        "cluster_id":         cluster_id,
        "name":               fb.get("name", f"Cluster {cluster_id}"),
        "tagline":            fb.get("tagline", ", ".join(top_skills[:4])),
        "pivot_reachability": fb.get("pivot_reachability", 3),
        "example_pivot_from": fb.get("example_pivot_from", ""),
        "eval_score":         0,   # 0 = fallback, not evaluated
        "refined":            False,
        "reasoning":          "API unavailable — pre-validated fallback name used.",
        "top_skills":         top_skills,
    }


def _all_fallbacks(cluster_themes: Dict[str, Any]) -> Dict[str, Dict[str, Any]]:
    return {
        cid: _fallback_cluster(cid, theme.get("top_skills", []))
        for cid, theme in cluster_themes.items()
    }
